    IN p_ClientID VARCHAR(50)
)
BEGIN
    DELETE FROM SupportTickets 
    WHERE UserID IN (SELECT UserID FROM Users WHERE ClientID = p_ClientID);

    DELETE FROM Clients WHERE ClientID = p_ClientID;
END //
