DROP PROCEDURE IF EXISTS DeleteRichardSmith;

DELIMITER //
CREATE PROCEDURE DeleteRichardSmith()
BEGIN
    UPDATE Employees SET ManagerID = NULL WHERE ManagerID = 'rsmith';
    DELETE FROM SupportTickets WHERE EmployeeID = 'rsmith';
    DELETE FROM Employees WHERE EmployeeID = 'rsmith';
END //
DELIMITER ;


-- InsertClient Procedure (Generated by Gemini)
DROP PROCEDURE IF EXISTS InsertClient;

DELIMITER //
CREATE PROCEDURE InsertClient (
    IN p_ClientID VARCHAR(50),
    IN p_ClientName VARCHAR(50),
    IN p_Revenue bigint
)
BEGIN
    INSERT INTO Clients (ClientID, ClientName, Revenue)
    VALUES (p_ClientID, p_ClientName, p_Revenue);
END //
DELIMITER ;


-- InsertProduct Procedure
DROP PROCEDURE IF EXISTS InsertProduct;

DELIMITER //
CREATE PROCEDURE InsertProduct (
    IN p_ProductID VARCHAR(50),
    IN p_ProductName VARCHAR(50)
)
BEGIN
    INSERT INTO Products (ProductID, ProductName)
    VALUES (p_ProductID, p_ProductName);
END //
DELIMITER ;

-- InsertUser Procedure
DROP PROCEDURE IF EXISTS InsertUser;

DELIMITER //
CREATE PROCEDURE InsertUser (
    IN p_UserID VARCHAR(50),
    IN p_fNameUser VARCHAR(50), 
    IN p_lNameUser VARCHAR(50),
    IN p_ClientID varchar(50), 
    IN p_Password varchar(50), 
    IN p_SecurityQuestion varchar(200), 
    IN p_SecurityAnswer varchar(50)
)
BEGIN
    INSERT INTO Users (UserID, fNameUser, lNameUser, ClientID, `Password`, SecurityQuestion, SecurityAnswer)
    VALUES (p_UserID, p_fNameUser, p_lNameUser, p_ClientID, p_Password, p_SecurityQuestion, p_SecurityAnswer);
END //
DELIMITER ;


